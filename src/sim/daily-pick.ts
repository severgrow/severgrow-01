// DAILY PUZZLE PICKER — from the generator's candidates to the shipped data file.
//
//   npx tsx src/sim/daily-pick.ts --in=a.jsonl,b.jsonl              ranked list of usable candidates
//   npx tsx src/sim/daily-pick.ts --in=... --pick=picks.json        writes src/daily/puzzles-data.ts
//
// `picks.json` is a list of { id, title, note } in day order: day 1 first. Every pick is PROVEN again
// here (exactly the build guard's check), so nothing unproven can be written.
import { readFileSync, writeFileSync } from 'node:fs';
import type { State } from '../engine/index.js';
import { prove } from '../daily/core.js';
import type { DailyGoal } from '../daily/core.js';

const arg = (name: string, fallback: string): string => {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : fallback;
};

type Candidate = {
  id: string; seed: number; turn: number; goal: DailyGoal; steps: number; solutions: number; ideas: string[];
  endings: number; nearMiss: number; level9Solves: boolean; hand: number; start: State;
};

const candidates: Candidate[] = arg('in', '').split(',').filter(Boolean).flatMap((f) =>
  readFileSync(f, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l) as Candidate));

/** The game always seats the player as player 0, so only positions where player 0 moves ship. */
const usable = candidates.filter((c) => c.start.turnPlayer === 0 && c.start.actor === 0);

/** Higher is harder: the search computer misses it, few answers, many tempting near-misses. */
const difficulty = (c: Candidate) =>
  (c.level9Solves ? 0 : 3) + (c.solutions === 1 ? 2 : c.solutions <= 3 ? 1 : 0) + Math.min(3, c.nearMiss / 4) + Math.min(2, Math.log10(c.endings) - 1.5);

const pickPath = arg('pick', '');
if (!pickPath) {
  const rows = usable.map((c) => ({ c, d: difficulty(c) })).sort((a, b) => b.d - a.d);
  for (const { c, d } of rows) {
    const goal = c.goal.kind === 'win' ? 'WIN' : `${c.goal.kind} ${c.goal.n}`;
    console.log([c.id.padEnd(22), goal.padEnd(10), `d=${d.toFixed(1)}`, `sol=${c.solutions}`, `end=${c.endings}`,
      `near=${c.nearMiss}`, c.level9Solves ? 'L9' : '--', `hand=${c.hand}`, c.ideas.join('+')].join('  '));
  }
  console.log(`${usable.length} usable of ${candidates.length}`);
  process.exit(0);
}

type Pick = { id: string; title: string; note: string };
const picks = JSON.parse(readFileSync(pickPath, 'utf8')) as Pick[];
const out: string[] = [];
for (const [i, p] of picks.entries()) {
  const c = usable.find((x) => x.id === p.id);
  if (!c) throw new Error(`no usable candidate ${p.id}`);
  const proof = prove({ start: c.start, goal: c.goal }, 50_000, 6);
  if (!proof.ok) throw new Error(`${p.id} does not prove: ${proof.reason}`);
  out.push(`  { no: ${i + 1}, title: ${JSON.stringify(p.title)}, note: ${JSON.stringify(p.note)}, source: ${JSON.stringify(p.id)}, goal: ${JSON.stringify(c.goal)}, start: ${JSON.stringify(c.start)} },`);
}
writeFileSync('src/daily/puzzles-data.ts', `// GENERATED by src/sim/daily-pick.ts from real games (see src/sim/daily-gen.ts). Do not edit by
// hand: change the picks and regenerate. Each entry is re-proven by tests/daily/puzzles.test.ts.
import type { DailyGoal } from './core.js';
import type { State } from '../engine/index.js';

export type PuzzleEntry = { no: number; title: string; note: string; source: string; goal: DailyGoal; start: State };

export const PUZZLE_DATA: readonly PuzzleEntry[] = [
${out.join('\n')}
];
`);
console.log(`wrote ${picks.length} puzzles`);
