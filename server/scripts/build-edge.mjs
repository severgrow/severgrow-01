#!/usr/bin/env node
// Bundle the duel API for Supabase Edge (Deno). postgres.js stays an npm: import at runtime.
// Writes supabase/functions/duel/bundle.ts. The tiny index.ts loader imports that file from GitHub
// (or you can `supabase functions deploy` with both files locally).
import * as esbuild from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = join(root, 'supabase/functions/duel');
const outFile = join(outDir, 'bundle.ts');
const loaderFile = join(outDir, 'index.ts');

mkdirSync(outDir, { recursive: true });

await esbuild.build({
  absWorkingDir: root,
  entryPoints: ['server/src/edge-entry.ts'],
  outfile: outFile,
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  legalComments: 'none',
  external: ['postgres'],
  logLevel: 'info',
});

let text = readFileSync(outFile, 'utf8');
text = text.replace(/from\s*["']postgres["']/g, 'from "npm:postgres@3.4.5"');
text = `// Auto-generated by server/scripts/build-edge.mjs — do not edit by hand.\n${text}`;
writeFileSync(outFile, text);

const loader = `// Tiny Edge entry: loads the MatchService bundle from this public repo (keeps MCP deploys small).
// After changing the API, run \`npm run server:build-edge\`, commit, push, then redeploy this function.
const BUNDLE_REF = Deno.env.get("BUNDLE_REF") ?? "futa0.5-online";
const url = \`https://raw.githubusercontent.com/severgrow/severgrow-01/\${BUNDLE_REF}/supabase/functions/duel/bundle.ts\`;
await import(url);
`;
if (!existsSync(loaderFile) || readFileSync(loaderFile, 'utf8').includes('Tiny Edge entry')) {
  writeFileSync(loaderFile, loader);
}

console.log(`wrote ${outFile} (${text.length} bytes)`);
console.log(`loader ${loaderFile} (${loader.length} bytes)`);
