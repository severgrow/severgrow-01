#!/usr/bin/env node
// Bundle the duel API for Supabase Edge (Deno). postgres.js stays an npm: import at runtime.
// Writes supabase/functions/duel/bundle.ts. The tiny index.ts loader imports that file from GitHub
// (or you can `supabase functions deploy` with both files locally).
import * as esbuild from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = join(root, 'supabase/functions/duel');
const outFile = join(outDir, 'bundle.ts');
const loaderFile = join(outDir, 'index.ts');

mkdirSync(outDir, { recursive: true });

await esbuild.build({
  absWorkingDir: root,
  entryPoints: ['server/src/edge-entry.ts'],
  outfile: outFile,
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  legalComments: 'none',
  external: ['postgres'],
  logLevel: 'info',
});

let text = readFileSync(outFile, 'utf8');

// Safety: never bake a credential-bearing connection string into the bundle. The secret must come
// from the Edge environment at runtime.
const credentialLeak = /postgres(?:ql)?:\/\/[^\s"'`\\]+:[^\s"'`\\]+@/.exec(text);
if (credentialLeak) {
  console.error('Refusing to write the bundle: it contains a database connection string with credentials.');
  process.exit(1);
}

// Regression guard on the Edge pool configuration. These options are what make the deployed
// function survive a shared, low-connection-limit project; if a refactor drops one, fail the build
// instead of shipping a quieter bug. postgres.js object keys are not minified, so a source check is
// reliable here.
const required = [
  [/prepare:\s*!1/, 'prepare: false (required for the Transaction pooler, port 6543)'],
  [/max:\s*[0-9]+/, 'a bounded pool `max`'],
  [/idle_timeout/, 'idle_timeout'],
  [/max_lifetime/, 'max_lifetime'],
  [/connect_timeout/, 'connect_timeout'],
  [/futasaku-duel-edge/, 'the application_name tag (connection diagnostics)'],
];
const missing = required.filter(([pattern]) => !pattern.test(text)).map(([, label]) => label);
if (missing.length > 0) {
  console.error(`Refusing to write the bundle: the Edge pool configuration is incomplete (${missing.join(', ')}).`);
  process.exit(1);
}

text = text.replace(/from\s*["']postgres["']/g, 'from "npm:postgres@3.4.5"');
text = `// Auto-generated by server/scripts/build-edge.mjs — do not edit by hand.\n${text}`;
writeFileSync(outFile, text);

const loader = `// Edge entry for \`supabase functions deploy\` (uploads index.ts + bundle.ts together).
import "./bundle.ts";
`;
writeFileSync(loaderFile, loader);

console.log(`wrote ${outFile} (${text.length} bytes)`);
console.log(`loader ${loaderFile} (${loader.length} bytes)`);
