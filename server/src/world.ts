// FUTASAKU world-map seed (spike).
//
// The SMALLEST proof that a finished duel can leave a PERMANENT mark on a SHARED map: one fixed,
// deterministic grid of 64 cells, the SAME for everyone. It is deliberately NOT a territory system
// — there is no ownership of regions, no income, no per-hex combat, no claim/defend rules.
//
// Everything in this module is PURE and deterministic: no randomness, no clock, no I/O. Placement
// is derived from data the server already owns (the server-generated match id and the match's two
// seats), never from anything a client sends, and never from the game engine.
//
// THE RULE (the smallest honest version of "beat the owner to take their tile"):
//   * Win a duel and you earn exactly one tile.
//   * If the player you just beat holds a tile, you TAKE it from them (the challenge rule).
//   * Otherwise you claim a free cell, picked from a hash of the match id so it is reproducible.
//   * If the map is full and your opponent holds nothing, you earn nothing.
import { sha256Hex } from './sha256.js';

/** The shared map is a fixed 8×8 grid, identical for every player. */
export const WORLD_MAP_COLS = 8;
export const WORLD_MAP_ROWS = 8;
export const WORLD_MAP_CELLS = WORLD_MAP_COLS * WORLD_MAP_ROWS;

/**
 * The deterministic starting cell for a match: the first 32 bits of the SHA-256 of the match id,
 * modulo the map size. The match id is generated by the SERVER, so a client can never steer where
 * its tile lands; a replay of the same match always computes the same cell.
 */
export const worldMapCell = (matchId: string): number =>
  Number.parseInt(sha256Hex(`futasaku.world.${matchId}`).slice(0, 8), 16) % WORLD_MAP_CELLS;

/** The minimum a tile must expose for placement to be decided: which cell, and whose it is. */
export type WorldCell = { cell: number; ownerId: string };

export type WorldPlacement =
  /** The winner takes the cell from the opponent they just beat. */
  | { kind: 'takeover'; cell: number }
  /** The winner claims a free cell. */
  | { kind: 'claim'; cell: number }
  /** Nothing to award: the map is full and the opponent held no tile. */
  | { kind: 'none' };

/**
 * The ONE placement decision, pure and total: given the map as it is now, who won and who lost,
 * what happens? The caller (the service) only has to execute it and retry on a lost race.
 */
export const planWorldPlacement = (input: {
  matchId: string;
  winnerId: string;
  loserId: string;
  tiles: readonly WorldCell[];
}): WorldPlacement => {
  const occupied = new Set(input.tiles.map((tile) => tile.cell));

  // 1. The challenge rule: you take one tile from the player you just beat. Lowest cell first, so
  //    the choice is deterministic and needs no extra bookkeeping.
  const victim = input.tiles
    .filter((tile) => tile.ownerId === input.loserId)
    .sort((a, b) => a.cell - b.cell)[0];
  if (victim) return { kind: 'takeover', cell: victim.cell };

  // 2. Otherwise a free cell, scanning forward from the match's own hash cell.
  const base = worldMapCell(input.matchId);
  for (let step = 0; step < WORLD_MAP_CELLS; step++) {
    const cell = (base + step) % WORLD_MAP_CELLS;
    if (!occupied.has(cell)) return { kind: 'claim', cell };
  }

  // 3. Map full, opponent holds nothing.
  return { kind: 'none' };
};
